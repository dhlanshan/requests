// Package logging 定义 requests 的日志扩展协议、结构化事件和默认日志实现。
//
// 本包仅依赖 Go 标准库，可独立使用，不依赖 requests 的 tn 或 internal 包。
// 请求执行层负责计时、计数和有界正文采集；本包负责快照隔离、脱敏及事件派发。
// 日志实现无需读取请求流，也无需了解执行层的重试与资源释放细节。
//
// Config 为 nil 表示关闭日志；非 nil Config 的 Logger 为 nil 时使用默认 slog 实现。
// 自定义 Logger 替换默认实现，不会重复打印。Logger 可被并发请求共享，Start 为每次
// 调用返回独立 Session。同一 Session 的回调由执行层串行触发，回调不得阻塞不返回。
//
// Header 和 Body 快照在派发前复制，接收者可保留它们，也可在自己的日志队列中异步处理。
// Err 保留原始错误链，仅供只读分类；默认实现不输出其原始文本。自定义 Redactor 可放宽
// 默认脱敏，但它只能修改日志副本，不会改变真实请求、响应或调用方收到的正文。
package logging
